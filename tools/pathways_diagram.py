# K9-AIF Framework
"""Draw where DAS sits: the requirement process feeding the six Adaptive Acquisition
Framework pathways, with Major Capability Acquisition expanded and the path DAS builds lit.

Sources (config/process_model.yaml): S2/S3 (JFRP, CJCSI 5123.01J / CJCSM 5123.01A),
S4 (DoWI 5000.02, the six pathways), S5 (DoDI 5000.85, MCA milestones and phases),
S6 (SE Guidebook, the technical reviews). Built vs designed comes from the process model.

    PYTHONPATH=src python tools/pathways_diagram.py [OUT_DIR]

Writes das-pathways.svg (light) and das-pathways-dark.svg to OUT_DIR
(default: src/k9_dow/api/static).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from k9_dow.config.process_model import load_process_model  # noqa: E402

THEMES = {
    "light": dict(bg="#ffffff", text="#1f2937", sub="#4b5563", faint="#9ca3af", line="#6b7280", box="#f9fafb",
                  das_fill="#eef4ff", das_line="#2563eb", hil_fill="#ecfdf5", hil_line="#059669",
                  lit="#d97706", lit_fill="#fff7ed"),
    "dark": dict(bg="#111a2e", text="#d3dae6", sub="#aab5c8", faint="#5f6b80", line="#7d889c", box="#16203a",
                 das_fill="#16264a", das_line="#6b9cf5", hil_fill="#10302a", hil_line="#34d399",
                 lit="#fbbf24", lit_fill="#2a2210"),
}

W, H = 1000, 540

PATHWAYS = ["Urgent Capability Acquisition", "Middle Tier of Acquisition", "Major Capability Acquisition",
            "Software Acquisition", "Defense Business Systems", "Acquisition of Services"]

# Major Capability Acquisition, left to right (DoDI 5000.85). kind: decision (a person decides; K9X HIL
# when built) | phase (DAS squads prepare when built). state: built | designed | later (not modelled).
MCA = [("MDD", "decision", "built", 50), ("MSA", "phase", "built", 60), ("MS A", "decision", "built", 50),
       ("TMRR", "phase", "partly", 178), ("MS B", "decision", "designed", 50), ("EMD", "phase", "later", 50),
       ("MS C", "decision", "later", 50), ("P&D", "phase", "later", 50), ("O&S", "phase", "later", 50)]
# Inside TMRR: the SE reviews and decision points before Milestone B (S5 3.8-3.9, S6).
TMRR_ITEMS = [("SRR", "built"), ("SFR", "designed"), ("CDD-equivalent validation", "designed"),
              ("PDR", "designed"), ("Development RFP Release", "designed")]


def _rect(x, y, w, h, fill, stroke, sw=1.5, dash=None, rx=7, opacity=None):
    extra = f' stroke-dasharray="{dash}"' if dash else ""
    extra += f' opacity="{opacity}"' if opacity else ""
    return (f'  <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" '
            f'stroke-width="{sw}"{extra}/>')


def _text(x, y, s, size, fill, weight=None, anchor=None):
    a = f' font-weight="{weight}"' if weight else ""
    a += f' text-anchor="{anchor}"' if anchor else ""
    s = s.replace("&", "&amp;")
    return f'  <text x="{x}" y="{y}" font-size="{size}" fill="{fill}"{a}>{s}</text>'


def _chip(c, x, y, w, h, label, kind, state):
    """A milestone/phase chip styled by what DAS does with it."""
    if state in ("built", "partly"):
        fill = c["hil_fill"] if kind == "decision" else c["das_fill"]
        stroke = c["lit"]
        out = [_rect(x, y, w, h, fill, stroke, sw=2.2)]
        col = c["text"]
    elif state == "designed":
        out = [_rect(x, y, w, h, c["box"], c["sub"], sw=1.2, dash="4 3")]
        col = c["sub"]
    else:
        out = [_rect(x, y, w, h, c["box"], c["faint"], sw=1, opacity="0.75")]
        col = c["faint"]
    out.append(_text(x + w / 2, y + 16, label, 11.5, col, weight="700", anchor="middle"))
    who = {"decision": "decision", "phase": "phase"}[kind]
    out.append(_text(x + w / 2, y + 30, who, 9, col if state != "later" else c["faint"], anchor="middle"))
    return out


def render(theme: str) -> str:
    c = THEMES[theme]
    pm = load_process_model()
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
           f'font-family="Helvetica, Arial, sans-serif">',
           f"  <!-- Requirement process and acquisition pathways, process model {pm.id} (as of {pm.as_of}). "
           f"Generated by tools/pathways_diagram.py; do not edit by hand. -->",
           "  <defs>",
           f'    <marker id="lit" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto">'
           f'<path d="M0,0 L10,5 L0,10 z" fill="{c["lit"]}"/></marker>',
           f'    <marker id="dim" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto">'
           f'<path d="M0,0 L10,5 L0,10 z" fill="{c["faint"]}"/></marker>',
           "  </defs>",
           f'  <rect width="{W}" height="{H}" fill="{c["bg"]}"/>',
           _text(20, 28, "Where DAS sits: requirement to acquisition, and the path this demo runs", 14, c["text"], "700"),
           _text(W - 20, 28, f"process model {pm.id} · current as of {pm.as_of}", 12, c["sub"], anchor="end")]

    # Pathway container (DoWI 5000.02)
    cx, cy, cw = 225, 52, 755
    rows_y = {}
    y = cy + 34
    for name in PATHWAYS:
        h = 150 if name == "Major Capability Acquisition" else 30
        rows_y[name] = (y, h)
        y += h + 8
    ch = y - cy + 4
    out.append(_rect(cx, cy, cw, ch, "none", c["line"], sw=1, rx=10))
    out.append(_text(cx + 14, cy + 22, "Adaptive Acquisition Framework: six pathways (DoWI 5000.02, S4)", 12.5, c["text"], "700"))

    for name in PATHWAYS:
        ry, rh = rows_y[name]
        if name != "Major Capability Acquisition":
            out.append(_rect(cx + 12, ry, cw - 24, rh, c["box"], c["sub"], sw=1, dash="4 3", rx=6))
            out.append(_text(cx + 26, ry + 19, name, 11.5, c["sub"], "600"))
            out.append(_text(cx + cw - 26, ry + 19, "designed, not built", 10, c["faint"], anchor="end"))
            continue
        out.append(_rect(cx + 12, ry, cw - 24, rh, c["lit_fill"], c["lit"], sw=2, rx=8))
        out.append(_text(cx + 26, ry + 20, "Major Capability Acquisition (DoDI 5000.85, S5)", 12, c["text"], "700"))
        out.append(_text(cx + cw - 26, ry + 20, "the path DAS builds: requirement → MDD → MSA → Milestone A → TMRR to the SRR",
                         10, c["lit"], "600", anchor="end"))
        x, top = cx + 26, ry + 34
        chip_y = {}
        for i, (label, kind, state, w) in enumerate(MCA):
            h = 104 if label == "TMRR" else 40
            if label == "TMRR":
                out.append(_rect(x, top, w, h, c["das_fill"], c["lit"], sw=2.2))
                out.append(_text(x + 10, top + 16, "TMRR", 11.5, c["text"], "700"))
                out.append(_text(x + w - 10, top + 16, "phase", 9, c["text"], anchor="end"))
                iy = top + 24
                for j, (item, st) in enumerate(TMRR_ITEMS):
                    iw = w - 20
                    if st == "built":
                        out.append(_rect(x + 10, iy, iw, 14, c["hil_fill"], c["lit"], sw=1.6, rx=4))
                        out.append(_text(x + 18, iy + 10.5, f"{item}  ✓ built", 9.5, c["text"], "700"))
                    else:
                        out.append(_rect(x + 10, iy, iw, 14, c["box"], c["sub"], sw=1, dash="3 2", rx=4))
                        out.append(_text(x + 18, iy + 10.5, item, 9.5, c["sub"]))
                    iy += 16
            else:
                out += _chip(c, x, top, w, h, label, kind, state)
            chip_y[label] = (x, w)
            if i < len(MCA) - 1:
                nxt_state = MCA[i + 1][2]
                lit_arrow = state in ("built", "partly") and nxt_state in ("built", "partly")
                ay = top + 20
                gap_end = x + w + 10
                out.append(f'  <line x1="{x + w + 2}" y1="{ay}" x2="{gap_end - 2}" y2="{ay}" '
                           f'stroke="{c["lit"] if lit_arrow else c["faint"]}" stroke-width="{2 if lit_arrow else 1.2}" '
                           f'marker-end="url(#{"lit" if lit_arrow else "dim"})"/>')
            x += w + 12
        mdd_x = chip_y["MDD"][0]
        mca_mdd_mid = top + 20

    # Requirement process (JFRP), left, feeding the acquisition side
    ry, rh = rows_y["Major Capability Acquisition"]
    bx, by, bw, bh = 20, ry, 180, rh
    out.append(_rect(bx, by, bw, bh, c["lit_fill"], c["lit"], sw=2, rx=8))
    out.append(_text(bx + 12, by + 20, "Requirement", 12.5, c["text"], "700"))
    out.append(_text(bx + 12, by + 35, "Joint Force Requirements Process", 9.5, c["sub"]))
    out.append(_text(bx + 12, by + 47, "(CJCSI 5123.01J, S2/S3)", 9.5, c["sub"]))
    for k, (label, note) in enumerate([("Service validation", "decision ✓ built"), ("JCI review", "parallel ✓ built")]):
        yy = by + 60 + k * 42
        out.append(_rect(bx + 12, yy, bw - 24, 34, c["hil_fill"], c["lit"], sw=1.8, rx=6))
        out.append(_text(bx + 22, yy + 15, label, 11, c["text"], "700"))
        out.append(_text(bx + 22, yy + 28, note, 9, c["text"]))
    # requirement → MDD (lit)
    out.append(f'  <path d="M {bx + bw} {by + 77} C {bx + bw + 30} {by + 77}, {mdd_x - 34} {mca_mdd_mid}, {mdd_x - 3} {mca_mdd_mid}" '
               f'fill="none" stroke="{c["lit"]}" stroke-width="2.2" marker-end="url(#lit)"/>')
    out.append(_text(bx + bw / 2, by + bh + 22, "JCIDS ended (S1, 2025-08-20);", 9.5, c["sub"], anchor="middle"))
    out.append(_text(bx + bw / 2, by + bh + 35, "JFRP replaces it (2026-08-05)", 9.5, c["sub"], anchor="middle"))

    # Legend
    ly = H - 66
    out.append(_rect(20, ly, 22, 13, c["lit_fill"], c["lit"], sw=2, rx=3))
    out.append(_text(48, ly + 11, "built in DAS: the path this demo runs (decisions in K9X HIL, phases by DAS squads)", 10.5, c["text"]))
    out.append(_rect(560, ly, 22, 13, c["box"], c["sub"], sw=1, dash="3 2", rx=3))
    out.append(_text(588, ly + 11, "designed, not built", 10.5, c["sub"]))
    out.append(_rect(730, ly, 22, 13, c["box"], c["faint"], sw=1, rx=3, opacity="0.75"))
    out.append(_text(758, ly + 11, "later phases, not modelled", 10.5, c["faint"]))
    out.append(_text(20, H - 30, "MDD Materiel Development Decision · MSA Materiel Solution Analysis · "
                     "TMRR Technology Maturation and Risk Reduction · MS Milestone", 9.5, c["sub"]))
    out.append(_text(20, H - 16, "EMD Engineering and Manufacturing Development · P&D Production and Deployment · "
                     "O&S Operations and Support · SRR / SFR / PDR System Requirements / System Functional / Preliminary Design Review",
                     9.5, c["sub"]))
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main():
    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "src" / "k9_dow" / "api" / "static"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "das-pathways.svg").write_text(render("light"), encoding="utf-8")
    (out_dir / "das-pathways-dark.svg").write_text(render("dark"), encoding="utf-8")
    print("wrote", out_dir / "das-pathways.svg", "and das-pathways-dark.svg")


if __name__ == "__main__":
    main()
